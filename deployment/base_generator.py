    def _set_optimization_parameters(self):
        """Set parameters based on optimization strategy and model complexity."""
        # Calculate complexity factors
        num_features = len(self.feature_names)
        num_classes = len(self.classes)
        complexity_factor = self._calculate_complexity_factor()

        if self.optimization == 'accuracy':
            self.sampling_rate = 100  # Higher sampling for better accuracy
            self.window_size = min(
                100, max(50, int(100 * complexity_factor)))  # Adaptive window
            self.feature_precision = 6  # Higher precision for features
            self.debug_enabled = True  # Enable detailed debugging
            self.buffer_optimization = False
        elif self.optimization == 'speed':
            # Adaptive speed optimization based on complexity
            base_sampling = 50
            if complexity_factor > 2.0:  # Very complex model
                self.sampling_rate = max(25, int(base_sampling / 1.5))
            elif complexity_factor > 1.5:  # Moderately complex
                self.sampling_rate = max(30, int(base_sampling / 1.2))
            else:
                self.sampling_rate = base_sampling

            self.window_size = min(50, max(25, int(50 / complexity_factor)))
            self.feature_precision = max(2, min(3, int(4 - complexity_factor)))
            self.debug_enabled = False  # Disable debugging for speed
            self.buffer_optimization = True
        elif self.optimization == 'power':
            # Ultra-conservative for power, more aggressive for complex models
            base_sampling = 25
            if complexity_factor > 2.0:  # Very complex model
                self.sampling_rate = max(15, int(base_sampling / 1.5))
            else:
                self.sampling_rate = base_sampling

            self.window_size = min(50, max(20, int(40 / complexity_factor)))
            self.feature_precision = max(1, min(2, int(3 - complexity_factor)))
            self.debug_enabled = False  # No debugging to save power
            self.buffer_optimization = True
        else:  # balanced
            # Balanced approach with slight adjustments for complexity
            if complexity_factor > 1.5:
                self.sampling_rate = 75  # Slightly lower for complex models
                self.window_size = 75
                self.feature_precision = 3
            else:
                self.sampling_rate = 100  # Standard sampling
                self.window_size = 100    # Standard window
                self.feature_precision = 4  # Balanced precision
            self.debug_enabled = False  # No debugging by default
            self.buffer_optimization = False

        # Apply final bounds checking
        self.sampling_rate = max(10, min(200, self.sampling_rate))
        self.window_size = max(20, min(200, self.window_size))
        self.feature_precision = max(1, min(8, self.feature_precision))

    def _calculate_complexity_factor(self) -> float:
        """
        Calculate model complexity factor based on features, classes, and model type.

        Returns:
            Float representing relative complexity (1.0 = baseline, >1.0 = more complex)
        """
        num_features = len(self.feature_names)
        num_classes = len(self.classes)

        # Base complexity from features and classes
        feature_factor = num_features / 50.0  # Normalize around 50 features
        class_factor = num_classes / 4.0      # Normalize around 4 classes

        # Model-type specific complexity multipliers
        model_multipliers = {
            'neural_network': 1.5,   # Neural networks are more complex
            'random_forest': 1.2,    # Random forests are moderately complex
            'svm': 1.3,              # SVMs can be complex
            'unknown': 1.0           # Default
        }

        model_multiplier = model_multipliers.get(self.model_type, 1.0)

        # Calculate overall complexity
        complexity = (feature_factor + class_factor) * model_multiplier / 2.0

        # Apply reasonable bounds
        return max(0.5, min(5.0, complexity))

    def _get_optimization_comment(self) -> str:
        """Get optimization-specific comment for generated code."""
        optimization_descriptions = {
            'accuracy': 'Optimized for maximum accuracy - higher sampling rate and precision',
            'speed': 'Optimized for fast inference - reduced sampling and simplified calculations',
            'power': 'Optimized for power efficiency - minimal sampling and low-power operations',
            'balanced': 'Balanced optimization - good trade-off between accuracy, speed, and power'
        }
        return optimization_descriptions.get(self.optimization, 'Standard configuration')

    def _validate_model_data(self, model_data: Dict[str, Any]) -> None:
        """
        Validate required model data fields and consistency.

        Args:
            model_data: Dictionary containing model parameters

        Raises:
            ModelDataError: If validation fails
        """
        if not isinstance(model_data, dict):
            raise ModelDataError("model_data must be a dictionary")

        # Check required fields
        required_fields = ['model_type', 'feature_names', 'classes']
        for field in required_fields:
            if field not in model_data:
                raise ModelDataError(f"Missing required field: '{field}'")

            value = model_data[field]
            if value is None:
                raise ModelDataError(f"Field '{field}' cannot be None")

            if field in ['feature_names', 'classes'] and not value:
                raise ModelDataError(f"Field '{field}' cannot be empty")

        # Validate model_type
        valid_model_types = ['random_forest',
                             'neural_network', 'svm', 'arm_cortex_m']
        if model_data['model_type'] not in valid_model_types:
            raise ModelDataError(f"Invalid model_type: '{model_data['model_type']}'. "
                                 f"Valid types: {valid_model_types}")

        # Validate feature_names
        feature_names = model_data['feature_names']
        if not isinstance(feature_names, list):
            raise ModelDataError("feature_names must be a list")

        if len(feature_names) < 1:
            raise ModelDataError("At least one feature is required")

        if len(feature_names) > 1000:
            raise ModelDataError("Too many features (max 1000 supported)")

        # Check for duplicate feature names
        if len(set(feature_names)) != len(feature_names):
            raise ModelDataError("Duplicate feature names are not allowed")

        # Validate classes
        classes = model_data['classes']
        if not isinstance(classes, list):
            raise ModelDataError("classes must be a list")

        if len(classes) < 2:
            raise ModelDataError(
                "At least two classes are required for classification")

        if len(classes) > 100:
            raise ModelDataError("Too many classes (max 100 supported)")

        # Check for duplicate class names
        if len(set(classes)) != len(classes):
            raise ModelDataError("Duplicate class names are not allowed")

    def _validate_optimization(self, optimization: str) -> None:
        """
        Validate optimization parameter.

        Args:
            optimization: Optimization level string

        Raises:
            OptimizationError: If validation fails
        """
        if not isinstance(optimization, str):
            raise OptimizationError("optimization must be a string")

        valid_optimizations = ['accuracy', 'speed', 'power', 'balanced']
        if optimization not in valid_optimizations:
            raise OptimizationError(f"Invalid optimization: '{optimization}'. "
                                    f"Valid options: {valid_optimizations}")

    def _validate_platform(self, platform: str) -> None:
        """
        Validate platform parameter.

        Args:
            platform: Target platform string

        Raises:
            ValidationError: If validation fails
        """
        if not isinstance(platform, str):
            raise ValidationError("platform must be a string")

        valid_platforms = ['arduino', 'arm_cortex_m',
                           'esp32', 'teensy', 'seeed_xiao']
        if platform not in valid_platforms:
            raise ValidationError(f"Invalid platform: '{platform}'. "
                                  f"Valid platforms: {valid_platforms}")

    def _validate_parameter_consistency(self) -> None:
        """
        Validate consistency between different model parameters.

        Raises:
            ModelDataError: If parameters are inconsistent
        """
        # Check feature scaling parameter consistency
        if 'feature_means' in self.model_data:
            means = self.model_data['feature_means']
            if not isinstance(means, list):
                raise ModelDataError("feature_means must be a list")

            if len(means) != len(self.feature_names):
                raise ModelDataError(f"feature_means length ({len(means)}) must match "
                                     f"feature_names length ({len(self.feature_names)})")

        if 'feature_stds' in self.model_data:
            stds = self.model_data['feature_stds']
            if not isinstance(stds, list):
                raise ModelDataError("feature_stds must be a list")

            if len(stds) != len(self.feature_names):
                raise ModelDataError(f"feature_stds length ({len(stds)}) must match "
                                     f"feature_names length ({len(self.feature_names)})")

            # Check for zero or negative standard deviations
            for i, std in enumerate(stds):
                if not isinstance(std, (int, float)) or std <= 0:
                    raise ModelDataError(
                        f"feature_stds[{i}] must be a positive number, got {std}")
